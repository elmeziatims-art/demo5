/* ---------- CONTROLE : a lancer AVANT et APRES ---------- */
SELECT  d.EXERCICE,
        SUM(d.CA)      AS CA,
        SUM(d.VARIABLE) AS VARIABLE,
        SUM(d.DIRECT)   AS DIRECT,
        MAX(d.SIEGE)    AS SIEGE,
        SUM(d.CA) - SUM(d.VARIABLE) - SUM(d.DIRECT) - MAX(d.SIEGE) AS EBITDA
FROM (
    SELECT  s.EXERCICE,
            SUM(s.VOL_EFF * s.REV_STUD + s.VOL_NEW * s.REV_FRAIS_INS) AS CA,
            0 AS VARIABLE, 0 AS DIRECT, 0 AS SIEGE
    FROM    AW_002_000002_000001 s GROUP BY s.EXERCICE
    UNION ALL
    SELECT  c.EXERCICE, 0,
            SUM(CASE WHEN c.ENTITY <> 'GRP' AND c.ACCOUNT IN ('621','604','6063','6231')
                     THEN c.AMOUNT ELSE 0 END),
            SUM(CASE WHEN c.ENTITY <> 'GRP' AND c.ACCOUNT IN ('6411','6413','645','613','615','616','625','63511')
                     THEN c.AMOUNT ELSE 0 END),
            0
    FROM    AW_002_000004_000001 c GROUP BY c.EXERCICE
    UNION ALL
    SELECT  c.EXERCICE, 0, 0, 0,
            SUM(CASE WHEN c.ACCOUNT IN ('6236','6414','6226','626','6281','6331','6333')
                     THEN c.AMOUNT ELSE 0 END)
    FROM    AW_002_000004_000001 c WHERE c.ENTITY = 'GRP' GROUP BY c.EXERCICE
) d
WHERE d.EXERCICE IN ('2024','2025','2026')
GROUP BY d.EXERCICE
ORDER BY d.EXERCICE;
